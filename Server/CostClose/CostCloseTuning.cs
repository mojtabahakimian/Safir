namespace Safir.Server.CostClose
{
    /// <summary>
    /// اعدادِ تنظیمیِ مشترکِ بستنِ ماه — یک‌جا، تا وقتی عوض می‌شوند در نه فایل
    /// پراکنده نمانند.
    /// </summary>
    public static class CostCloseTuning
    {
        /// <summary>
        /// مهلتِ اجرای دستورهای دسته‌ایِ بازسازی (ثانیه).
        ///
        /// چرا نه پیش‌فرضِ ۳۰ ثانیه‌ی Dapper: این دستورها صدها INSERT/DELETE را
        /// در یک رفت‌وبرگشت می‌فرستند و هم‌زمان با پایپ‌لاینِ در حال اجرا سرِ
        /// قفلِ DEED_DTL رقابت می‌کنند. خرداد ۱۴۰۵ روی «برگشت فروش»:
        /// «Execution Timeout Expired» درحالی‌که شمارشِ همان شرط ۳٫۸ ثانیه طول
        /// می‌کشید و صفر ردیف برمی‌گرداند — یعنی انتظارِ قفل بود، نه کندی.
        ///
        /// نیمه‌کاره رها شدنِ یک بازسازی از دیر تمام شدنش بدتر است: سند
        /// حسابداریِ ناقص می‌ماند و CHK-02 مغایرت کاذب نشان می‌دهد.
        ///
        /// ⚠️ عمداً فقط روی همین دستورهای سنگین نشسته، نه روی پیش‌فرضِ
        /// IDatabaseService: کوئری‌های عادیِ رابط کاربری باید همان ۳۰ ثانیه
        /// بمانند تا یک کوئریِ گیرکرده صفحه را ده دقیقه معطل نکند.
        /// </summary>
        public const int BatchTimeoutSeconds = 600;
    }
}
