    /// <summary>
    /// مدل با این ابزار توضیح یک حوزه را می‌گیرد، به‌جای اینکه کل
    /// دیکشنری در هر پیام فرستاده شود.
    /// </summary>
    public sealed class DescribeDataTool : IAiTool
    {
        public string Name        => "describe_data";
        public string Title       => "توضیح جدول‌ها و معنی ستون‌ها";
        public string Description => "توضیح یک حوزه از پایگاه داده و معنی ستون‌هایش. " +
                                     "پیش از نوشتن هر کوئری درباره‌ی حوزه‌ای که مطمئن نیستی، " +
                                     "این را صدا بزن.";

        // این ابزار داده‌ی شرکت را برنمی‌گرداند، فقط توضیح ساختار — پس
        // همان دسترسیِ دیدنِ داشبورد کافی است.
        public string RequiredForm => Safir.Shared.Constants.CostForms.Dashboard;
        public Safir.Server.Security.Pay2Perm RequiredPerm
            => Safir.Server.Security.Pay2Perm.See;

        public string Parameters => "section: core | costclose | accounting";

        public Task<AiToolResult> ExecuteAsync(AiToolCall call, CancellationToken ct = default)
        {
            var section = call.Str("section") ?? "core";

            if (!AiDataDictionary.Sections.TryGetValue(section, out var text))
                return Task.FromResult(AiToolResult.Fail(
                    "بخش نامعتبر. یکی از این‌ها: " +
                    string.Join(", ", AiDataDictionary.Sections.Keys)));

            return Task.FromResult(new AiToolResult { Rows = 1, Data = text });
        }
    }
