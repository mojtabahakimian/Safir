IF COL_LENGTH('dbo.CC_CheckRule', 'IsBlocking') IS NULL
BEGIN
    ALTER TABLE dbo.CC_CheckRule
        ADD IsBlocking BIT NOT NULL CONSTRAINT DF_CC_CheckRule_IsBlocking DEFAULT (0);

    PRINT N'ستون IsBlocking به CC_CheckRule اضافه شد.';
END
GO

/* پیش‌فرض صفر است، پس فقط همان یکی را روشن می‌کنیم.
   عمداً بی‌قید نوشته شده و نه «فقط اگر قبلاً تنظیم نشده»: این اسکریپت
   قاعده‌ی پایه را برمی‌گرداند. اگر نصبی عمداً چیز دیگری خواسته، بعد از
   اجرای این، تنظیمِ خودش را دوباره اعمال کند. */
UPDATE dbo.CC_CheckRule SET IsBlocking = 1 WHERE RuleCode = 'CHK-01';
UPDATE dbo.CC_CheckRule SET IsBlocking = 0 WHERE RuleCode <> 'CHK-01';
GO

SELECT  RuleCode, RuleName, DefaultSeverity AS شدت_نمایشی, IsBlocking AS متوقف_کننده
FROM    dbo.CC_CheckRule
ORDER BY IsBlocking DESC, RuleCode;
GO

PRINT N'قاعده‌ی توقف تنظیم شد: فقط کاردکس منفی (CHK-01) اجرا را متوقف می‌کند.';
GO
