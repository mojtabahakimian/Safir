/* ═══════════════════════════════════════════════════════════════════
   کدام کنترل اجازه دارد اجرا را متوقف کند

   ── مسئله ──
   تا امروز دروازه‌ی S05 هر استثنایی با Severity=2 را «مسدودکننده»
   می‌شمرد. ده قاعده این شدت را دارند، و روی یک ماهِ واقعی یعنی اجرا
   پشتِ CHK-02 (۲۲۳ مورد) و CHK-17 (۴۸ مورد) می‌ایستد.

   ولی ترتیبِ کارِ صاحب پروژه این نیست. او CHK-02 را در گامِ *ششم*
   رفع می‌کند — بعد از صدور اسناد گروهی — چون تا آن اسناد صادر نشوند،
   مغایرتِ کاردکس و حسابداری اصلاً معنا ندارد. ایستادنِ اجرا پشتِ آن،
   جلوی همان کاری را می‌گیرد که قرار است رفعش کند.

   قاعده‌ی او دقیقاً این است:
     «کاردکس منفی توقف ایجاد کند، ولی به غیر از آن اجرا باید ادامه
      داشته باشد.»

   ── چرا فقط کاردکس منفی ──
   کاردکس منفی تنها موردی است که *محاسبه* را خراب می‌کند، نه اینکه
   فقط گزارش دهد: میانگین متحرک در لحظه‌ی منفی‌شدن بر مقدارِ منفی یا
   نزدیک صفر تقسیم می‌شود و نرخ از آنجا به بعد بی‌معنا می‌ماند. ادامه
   دادن با آن، یعنی ساختنِ یک ماهِ کامل روی عددِ غلط.
   بقیه‌ی کنترل‌ها گزارشِ وضعیت‌اند؛ باید دیده شوند، ولی جلوی کار را
   نگیرند.

   ── چرا ستون جدا و نه استفاده از Severity ──
   Severity برای *نمایش* است (رنگ و ترتیب در فهرست استثناها). اگر
   همان را معیارِ توقف هم بگیریم، هر بار که بخواهیم اهمیتِ نمایشیِ
   چیزی را بالا ببریم، ناخواسته اجرا را هم متوقف می‌کنیم. این دو
   تصمیمِ جدا هستند و ستونِ جدا می‌خواهند.

   ستون تنظیم‌پذیر است: اگر روزی نصبی بخواهد کنترلِ دیگری هم متوقف
   کند، یک UPDATE کافی است و کد عوض نمی‌شود — همان الگویی که Threshold
   دارد.
