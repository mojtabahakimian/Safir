-- ================================================================
-- PAY2 — قاعده‌ی عدم مشمولیت مالیاتِ «حق شیفت و اضافه‌کار»
-- ================================================================
-- چرا این تنظیم لازم شد
-- --------------------
-- برای بیمه از قبل یک کلید تاریخ‌دار وجود داشت:
--     INS_NON_SUBJECT_EFFECTIVE_FROM
-- که SHIFT / OT_NORMAL / OT_HOLIDAY / OT_ADMIN را از مبنای بیمه کنار
-- می‌گذارد و چون در موتور *بعد از* حل شدن Overrideها اجرا می‌شود، حتی
-- INS_OV=1 روی حکمِ قفل‌شده را هم خنثی می‌کند.
--
-- ولی هیچ معادلی برای مالیات نبود، و نبودش صرفاً «ناقص» نیست — نتیجه را
-- برعکس می‌کند. یک نمونه‌ی واقعی (تیر ۱۴۰۵):
--
--   دستمزد ماهانه اسمی                     297,930,615
--   بن + مسکن + حق تاهل                     60,000,000
--   حق شیفت (۲۲٫۵٪ ریل اسمی)                67,034,388
--   حق اولاد (معاف بیمه، مشمول مالیات)      33,251,100
--   معافیت مالیاتی ماهانه ۱۴۰۵            400,000,000
--
--   وضعیت اول (حق شیفت در بیمه و مالیات):
--     مبنای بیمه   = 424,965,003  →  بیمه سهم کارگر = 29,747,550
--     مبنای مالیات = 458,216,103 − 29,747,550 − 400,000,000 = 28,468,553
--     مالیات       = ۱۰٪ → 2,846,855
--
--   وضعیت دوم (فقط کلید بیمه روشن شود):
--     مبنای بیمه   = 357,930,615  →  بیمه سهم کارگر = 25,055,143
--     مبنای مالیات = 458,216,103 − 25,055,143 − 400,000,000 = 33,160,960
--     مالیات       = ۱۰٪ → 3,316,096   ← بیشتر از قبل!
--
--   وضعیت سوم (هر دو کلید روشن):
--     مبنای مالیات = 391,181,715 − 25,055,143 = 366,126,572 < معافیت
--     مالیات       = 0
--
-- یعنی روشن کردنِ تنهای کلید بیمه مالیات را بالا می‌برد، چون بیمه‌ی سهم
-- کارگرِ کسرشدنی از مبنای مالیات کوچک‌تر می‌شود در حالی که خود حق شیفت
-- هنوز داخل آن مبناست.
--
-- تفاوت با کلید بیمه
-- -------------------
-- کلید بیمه با یک Procedure یک‌بارمصرف (SP_PAY2_APPLY_INS_NON_SUBJECT_OPTIN)
-- ست می‌شود چون آن Procedure ستون INS_SUBJECT جدول PAY2_ITEM_DEF را هم
-- بازنویسی می‌کند. این کلید هیچ داده‌ای را بازنویسی نمی‌کند و فقط هنگام
-- محاسبه خوانده می‌شود، پس مثل بقیه‌ی تنظیمات حساس (ACCESS_LEVEL=1) از
-- صفحه‌ی «تنظیمات حقوق و دستمزد» ست می‌شود و برگشت‌پذیر است.
--
-- منبع حقیقتِ خودِ موتور
-- -----------------------
-- بدنه‌ی SP_PAY2_CALC_RUN در مخزن ScriptSqly است (طبق AGENTS.md بخش ۹)،
-- فایل ScriptSqly.Core/ScriptSqly.Salary.cs. این اسکریپت فقط کلید تنظیمات
-- را نصب می‌کند؛ برای اعمال قاعده باید Updater هم اجرا شود.
-- ================================================================

SET NOCOUNT ON;
GO

IF NOT EXISTS (SELECT 1 FROM dbo.PAY2_CONFIG WHERE CFG_KEY = N'TAX_NON_SUBJECT_EFFECTIVE_FROM')
    INSERT dbo.PAY2_CONFIG (CFG_KEY, CFG_VALUE, CFG_OPTIONS, CFG_DEFAULT, CFG_SECTION, LABEL_FA, DESC_FA, OPT_LABELS, DATA_TYPE, ACCESS_LEVEL)
    VALUES (N'TAX_NON_SUBJECT_EFFECTIVE_FROM', N'0', NULL, N'0', N'مالیات',
            N'تاریخ اثر عدم مشمولیت مالیاتِ شیفت و اضافه‌کار',
            N'تاریخ شمسی روز اول ماه (مثلاً 14050401). صفر یعنی خاموش و رفتار پیش‌فرض برقرار است: شیفت و اضافه‌کار مشمول مالیات‌اند. فعال کردن، مالیات این اقلام را از همان ماه به بعد صفر می‌کند؛ مسئولیت قانونی با کارفرماست.',
            NULL, N'DATE', 1);
GO

-- راستی‌آزمایی
SELECT CFG_KEY, CFG_VALUE, CFG_DEFAULT, CFG_SECTION, DATA_TYPE, ACCESS_LEVEL
FROM dbo.PAY2_CONFIG
WHERE CFG_KEY IN (N'INS_NON_SUBJECT_EFFECTIVE_FROM', N'TAX_NON_SUBJECT_EFFECTIVE_FROM')
ORDER BY CFG_KEY;
GO
