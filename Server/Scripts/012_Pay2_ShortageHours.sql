-- ============================================================================
-- PAY2 — افزودن ستون «کسر کار» (SHORTAGE_H) به کارکرد ماهانه
--
-- ساعات ثبت‌شده در این ستون با ضریب ۱.۰ (نرخ یک ساعت کار عادی، بدون ضریب
-- اضافه‌کار) محاسبه و در موتور محاسبه (SP_PAY2_CALC_RUN) به کسورات ماه
-- (سایر کسورات) افزوده می‌شود.
--
-- ⚠️ بدنه به‌روزشدهٔ SP_PAY2_CALC_RUN در Server/Info/ScriptSqly.cs قرار دارد و
--    توسط آپدیتر دیتابیس اعمال می‌شود؛ این اسکریپت فقط تغییر ساختار جدول است.
-- ============================================================================

IF COL_LENGTH('dbo.PAY2_ATTENDANCE', 'SHORTAGE_H') IS NULL
    ALTER TABLE dbo.PAY2_ATTENDANCE
        ADD SHORTAGE_H DECIMAL(6,2) NOT NULL CONSTRAINT DF_ATT_SHRT DEFAULT(0);
GO
