-- ============================================================================
-- PAY2 — نسبت‌گیری اقلام ماهیانه با تفکیک کارکرد اسمی و رسمی
--
-- گزارش مشتری: برای پرسنل با کارکرد ناقص، خواربار و مسکن و بن کارگری به‌نسبت
-- کارکرد کم می‌شوند ولی «حق تأهل» کامل پرداخت می‌شود.
--
-- ریشه: حق تأهل (FAMILY_ALLOW) و بقیه اقلام ماهیانه CALC_BASIS = 2 دارند و در
-- شاخه جداگانه‌ای از SP_PAY2_CALC_RUN محاسبه می‌شوند که رفتارش با کلید تنظیمات
-- MONTHLY_ITEM_PRORATE کنترل می‌شود (پیش‌فرض 0 = پرداخت کامل).
--
-- اما روشن‌کردن آن کلید به‌تنهایی کافی نبود: شاخه اقلام ماهیانه مبلغ بیمه/مالیات
-- را کورکورانه از مبلغ پرداختی کپی می‌کرد (INS_CALC_AMOUNT = CALC_AMOUNT) و دو
-- ریل کارکرد را از هم جدا نمی‌کرد. در نتیجه در کارگاه‌هایی که بیمه را کامل رد
-- می‌کنند ولی پرداختی را به‌نسبت کارکرد می‌دهند (کارکرد اسمی ≠ کارکرد رسمی)،
-- مبلغِ اظهارشده به بیمه و مالیات هم به‌اشتباه کم می‌شد.
--
-- اصلاح: شاخه CALC_BASIS = 2 وقتی MONTHLY_ITEM_PRORATE = 1 است دقیقاً همان
-- قاعده خواربار و مسکن/بن کارگری را به کار می‌برد:
--     • مخرج ثابت ۳۰ روز (نه روزهای واقعی ماه) — هم‌خوان با مسکن و بن
--     • آستانه «۲۸ روز و بیشتر = ماه کامل»
--     • دو ریل جدا طبق PAY_BASE_DAYS و INS_BASE_DAYS آیتم:
--           پرداختی      ← کارکرد رسمی (DAYSB)
--           بیمه/مالیات  ← کارکرد اسمی (DAYS)
--
-- وقتی MONTHLY_ITEM_PRORATE = 0 باشد رفتار هیچ تغییری نمی‌کند؛ این اصلاح تا
-- روشن‌شدن آن کلید کاملاً بی‌اثر است.
--
-- آیتم‌های تحت تأثیر (هر آیتمی با CALC_BASIS = 2): حق تأهل، حق جذب،
-- شرایط محیط کار، سایر ثابت، حق مسئولیت، پاداش/راندمانِ ثبت‌شده در حکم.
--
-- ⚠️ این تغییر فقط در بدنه SP_PAY2_CALC_RUN است و ساختار جدولی ندارد. بدنه
--    به‌روزشده در مخزن ScriptSqly (ScriptSqly.Core/ScriptSqly.Salary.cs) قرار
--    دارد و توسط آپدیتر دیتابیس اعمال می‌شود. این فایل مستندسازی و بررسی است.
-- ============================================================================

-- ── بررسی وضعیت تنظیمات کارگاه ──────────────────────────────────────────────
SELECT CFG_KEY, CFG_VALUE, CFG_DEFAULT, LABEL_FA
FROM   PAY2_CONFIG
WHERE  CFG_KEY IN ('MONTHLY_ITEM_PRORATE', 'MONTH_DAYS_MODE');
GO

-- ── اقلامی که با روشن‌کردن این کلید نسبت‌گیری خواهند شد ─────────────────────
SELECT ITEM_ID, ITEM_CODE, ITEM_NAME, CALC_BASIS, INS_BASE_DAYS, PAY_BASE_DAYS
FROM   PAY2_ITEM_DEF
WHERE  IS_ACTIVE = 1 AND CALC_BASIS = 2
ORDER  BY SORT_ORDER;
GO

-- ── تفکیک کارکرد اسمی/رسمی در دوره جاری (اگر برابر نباشند دو ریل فعال است) ──
SELECT A.PER_ID, A.EMP_ID, E.EMP_CODE, E.FIRST_NAME + N' ' + E.LAST_NAME AS FULL_NAME,
       A.WORK_DAYS, A.DAYS AS DAYS_ESMI_INS, A.DAYSB AS DAYSB_RASMI_PAY
FROM   PAY2_ATTENDANCE A
       INNER JOIN PAY2_EMPLOYEE E ON E.EMP_ID = A.EMP_ID
WHERE  A.DAYS <> A.DAYSB
ORDER  BY A.PER_ID DESC, E.EMP_CODE;
GO
